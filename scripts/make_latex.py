"""Build the Overleaf LaTeX sources from generated results only.

Writes paper/latex/numbers.tex (one macro per generated value) and paper/latex/tables/*.tex
(from tables/*.csv), and copies the figures and the bibliography. The prose in
paper/latex/main.tex is hand-written and must reference the macros, never literal results;
scripts/audit_latex.py enforces that.

    .venv/Scripts/python.exe scripts/make_latex.py
"""
import argparse
import json
from pathlib import Path
import re
import shutil

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'paper/latex'
FIGURES = ['fig_learning_curve', 'fig_cost_performance', 'fig_ablations',
           'fig_error_overlap', 'fig_reliability']
WORDS = {'0': 'Zero', '1': 'One', '2': 'Two', '3': 'Three', '4': 'Four', '5': 'Five',
         '6': 'Six', '7': 'Seven', '8': 'Eight', '9': 'Nine', '10': 'Ten', '15': 'Fifteen',
         '16': 'Sixteen', '18': 'Eighteen', '100': 'Hundred'}
# Ablation variant -> (display name, main method it is a variant of).
ABLATIONS = {'lora_last2': ('LoRA, last 2 blocks', 'LoRA'),
             'lora_rank4': ('LoRA, rank 4', 'LoRA'),
             'lora_rank16': ('LoRA, rank 16', 'LoRA'),
             'lora_no_augmentation': ('LoRA, no augmentation', 'LoRA'),
             'pft_depth4': ('PFT, last 4 blocks', 'PFT')}
VERDICT = {'a_better': 'yes', 'b_better': 'yes', 'a_larger_gap': 'yes',
           'b_larger_gap': 'yes', 'no_detectable_difference': 'no'}
# Author names in refs.bib carry diacritics. Braced LaTeX escapes keep the bibliography
# ASCII and render the names correctly; an unmapped character is an error, never dropped.
DIACRITICS = {'é': "{\\'{e}}", 'ë': '{\\"{e}}', 'ü': '{\\"{u}}',
              'ö': '{\\"{o}}', 'ç': '{\\c{c}}', 'ł': '{\\l}',
              'Ł': '{\\L}', 'Ć': "{\\'{C}}", 'ń': "{\\'{n}}",
              'ś': "{\\'{s}}", 'Ż': '{\\.{Z}}', 'ğ': '{\\u{g}}',
              'ı': '{\\i}'}
# The contrasts the article reports, declared here so the prose quotes generated cells only.
# (a method, b method, fraction, cohort, kind, hypothesis)
REPORTED = ([('LP', 'LoRA', .01, 'internal', 'auc', 'H1'),
             ('LP', 'LoRA', 1., 'internal', 'auc', 'H1')]
            + [('LP', 'PFT', 1., 'internal', 'auc', 'H2'),
               ('LP', 'PFT', 1., 'external', 'auc', 'H2'),
               ('LP', 'LoRA', 1., 'external', 'auc', 'H2'),
               ('PFT', 'LoRA', .1, 'external', 'auc', 'H2'),
               ('PFT', 'LoRA', 1., 'external', 'auc', 'H2'),
               ('LP', 'PFT', 1., 'internal_minus_external', 'gap', 'H2'),
               ('LP', 'LoRA', 1., 'internal_minus_external', 'gap', 'H2'),
               ('PFT', 'LoRA', 1., 'internal_minus_external', 'gap', 'H2')]
            + [(m, 'CNN', f, c, 'auc', 'H3')
               for c in ('internal', 'external') for f in (.01, .1)
               for m in ('LP', 'PFT', 'LoRA')])


def digits(run: str) -> str:
    return WORDS.get(run) or ''.join(WORDS[d] for d in run)


def macro_name(key: str) -> str:
    name = 'val'
    for part in key.split('.'):
        for piece in re.split(r'[^A-Za-z0-9]+', part):
            if not piece:
                continue
            chunks = re.findall(r'[A-Za-z]+|\d+', piece)
            rendered = ''.join(digits(c) if c.isdigit() else c[0].upper() + c[1:] for c in chunks)
            name += rendered
    return name


def escape(value: str) -> str:
    """LaTeX-safe rendering of a generated value, ASCII only."""
    text = str(value)
    text = text.replace('\\', r'\textbackslash{}')
    for char in ('&', '%', '$', '#', '_', '{', '}'):
        text = text.replace(char, '\\' + char)
    text = text.replace('±', r'$\pm$').replace('×', r'$\times$')
    text = text.replace('−', '-').replace('–', '--').replace('—', '---')
    text = text.replace('°', r'$^\circ$').replace('≤', r'$\leq$')
    # A body starting with '[' would be read as an optional argument after \\ in a table.
    text = text.replace('[', '{[}').replace(']', '{]}')
    # Render a leading minus as a real minus sign.
    text = re.sub(r'(?<![\d.])-(?=\d)', r'$-$', text)
    return text


def load_values() -> dict[str, str]:
    values = {}
    for name in ('numbers_protocol.json', 'numbers.json'):
        path = ROOT / 'paper' / name
        values.update(json.loads(path.read_text(encoding='utf-8'))['values'])
    return values


def write_numbers(values: dict[str, str]) -> int:
    lines = ['% Generated by scripts/make_latex.py from paper/numbers*.json. Do not edit.',
             '% Every macro is one value produced from results/ or the frozen contract.', '']
    seen = {}
    for key in sorted(values):
        name = macro_name(key)
        if name in seen:
            raise SystemExit(f'Macro collision: {key} and {seen[name]} both give \\{name}')
        seen[name] = key
        lines.append(f'\\newcommand{{\\{name}}}{{{escape(values[key])}\\xspace}}% {key}')
    (OUT / 'numbers.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    return len(seen)


def tabular(columns: str, header: list[str], rows: list[list[str]], size='\\footnotesize') -> str:
    body = [f'{size}', f'\\begin{{tabular}}{{{columns}}}', '\\toprule',
            ' & '.join(header) + ' \\\\', '\\midrule']
    body += [' & '.join(r) + ' \\\\' for r in rows]
    body += ['\\bottomrule', '\\end{tabular}']
    return '\n'.join(body) + '\n'


def cell(value) -> str:
    return escape('' if pd.isna(value) else value)


def table_main() -> str:
    frame = pd.read_csv(ROOT / 'tables/main_results.csv')
    rows = [[cell(r.Method), cell(r.Labels), cell(r.AUC_in), cell(r._4), cell(r.AUC_out),
             cell(r._6), cell(r.Gap), cell(r.F1_in), cell(r.F1_out), cell(r.ECE_in),
             cell(r.ECE_out)] for r in frame.itertuples()]
    header = ['Method', 'Labels', 'AUC$_\\mathrm{in}$', '95\\% CI', 'AUC$_\\mathrm{out}$',
              '95\\% CI', 'Gap', 'F1$_\\mathrm{in}$', 'F1$_\\mathrm{out}$',
              'ECE$_\\mathrm{in}$', 'ECE$_\\mathrm{out}$']
    return tabular('llccccccccc', header, rows, '\\scriptsize')


def table_cost() -> str:
    frame = pd.read_csv(ROOT / 'tables/cost.csv')
    rows = [[cell(v) for v in row] for row in frame.values]
    header = ['Method', 'Labels', 'Trainable', 'Charged (s)', 'To best (s)', 'Epochs',
              'Cap hit', 'Peak RSS (GiB)', 'Inference (ms/img)']
    return tabular('llrrrrccc', header, rows, '\\scriptsize')


def table_hypotheses() -> str:
    data = json.loads((ROOT / 'tables/hypotheses.json').read_text(encoding='utf-8'))
    labels = {'LP_not_worse_than_LoRA_at_1pct': 'LP not worse than LoRA at 1\\% (internal)',
              'LoRA_beats_LP_at_100pct': 'LoRA beats LP at 100\\% (internal)',
              'ranking_preserved_externally': 'Internal ranking preserved externally',
              'gap_does_not_grow_with_trainable_parameters':
                  'Gap does not grow with trainable parameters',
              'H3': 'All three FM strategies beat the scratch CNN at 1\\% and 10\\% (internal)',
              'H3_external_secondary': 'Same six contrasts on the external cohort'}
    rows = []
    for name in ('H1', 'H2'):
        clauses = data[name]['clauses']
        for clause, verdict in clauses.items():
            rows.append([name, labels[clause], f'\\emph{{{verdict}}}'])
        rows.append([f'\\textbf{{{name}}}', '\\textbf{compound}',
                     f'\\textbf{{{data[name]["verdict"]}}}'])
    rows.append(['\\textbf{H3}', f'\\textbf{{{labels["H3"]}}}',
                 f'\\textbf{{{data["H3"]["verdict"]}}}'])
    rows.append(['H3$^{*}$', labels['H3_external_secondary'],
                 f'\\emph{{{data["H3_external_secondary"]["verdict"]}}}'])
    return tabular('lll', ['', 'Clause', 'Verdict'], rows)


def table_ablations() -> str:
    frame = pd.read_csv(ROOT / 'tables/ablations.csv')
    contrasts = pd.read_csv(ROOT / 'tables/contrasts.csv')
    rows = []
    for r in frame.itertuples():
        display, reference = ABLATIONS[r.Variant]
        fraction = {'1%': .01, '10%': .1, '100%': 1.}[r.Labels]
        method = reference if not r.Variant.startswith('pft') else 'PFT'
        match = contrasts[(contrasts.a == f'{r.Variant}:{method}')
                          & (contrasts.b == f'main:{reference}')
                          & (contrasts.cohort == 'external')
                          & (contrasts.fraction.round(4) == round(fraction, 4))]
        if len(match) != 1:
            raise SystemExit(f'Expected one external contrast for {r.Variant} {r.Labels}')
        row = match.iloc[0]
        delta = escape(f'{row.mean_difference:+.3f} [{row.ci95_lower:+.3f}, '
                       f'{row.ci95_upper:+.3f}]')
        rows.append([display, escape(r.Labels), escape(r._4), escape(r.AUC_in),
                     escape(r.AUC_out), f'{reference}', delta, VERDICT[row.direction]])
    header = ['Variant', 'Labels', 'Trainable', 'AUC$_\\mathrm{in}$', 'AUC$_\\mathrm{out}$',
              'vs.', '$\\Delta$ AUC$_\\mathrm{out}$ [95\\% CI]', 'Detect.']
    return tabular('llrcclcc', header, rows, '\\scriptsize')


def table_contrasts() -> str:
    frame = pd.read_csv(ROOT / 'tables/contrasts.csv')
    cohorts = {'internal': 'internal', 'external': 'external',
               'internal_minus_external': 'gap'}
    rows = []
    for a, b, fraction, cohort, kind, hypothesis in REPORTED:
        match = frame[(frame.a == f'main:{a}') & (frame.b == f'main:{b}')
                      & (frame.kind == kind) & (frame.cohort == cohort)
                      & (frame.fraction.round(4) == round(fraction, 4))]
        if len(match) != 1:
            raise SystemExit(f'Expected one row for {a} vs {b} {fraction} {cohort} {kind}')
        row = match.iloc[0]
        rows.append([hypothesis, f'{a} $-$ {b}', f'{int(round(100 * fraction))}\\%',
                     cohorts[cohort], escape(f'{row.mean_difference:+.3f}'),
                     f'{row.larger_method_sd:.3f}',
                     escape(f'[{row.ci95_lower:+.3f}, {row.ci95_upper:+.3f}]'),
                     VERDICT[row.direction]])
    header = ['', 'Contrast', 'Labels', 'Cohort', '$\\Delta$ mean', 'Larger SD',
              '95\\% CI of $\\Delta$', 'Detect.']
    return tabular('llccrrcc', header, rows, '\\scriptsize')


def table_strata() -> str:
    frame = pd.read_csv(ROOT / 'tables/error_strata_all.csv')
    frame = frame[(frame.fraction == 1.) & frame.variable.isin(['BIRADS', 'Verification'])]
    rows = []
    for (variable, category), group in frame.groupby(['variable', 'category'], sort=False):
        indexed = group.set_index('method')
        n = int(indexed.n.iloc[0])
        malignant = int(indexed.n_malignant.iloc[0])
        label = ('BI-RADS ' + str(category)) if variable == 'BIRADS' else str(category).capitalize()
        cells = [f'{indexed.loc[m].error_rate_mean:.2f} $\\pm$ {indexed.loc[m].error_rate_sd:.2f}'
                 for m in ('LP', 'PFT', 'LoRA', 'CNN')]
        rows.append([escape(label), str(n), str(malignant)] + cells)
    header = ['External stratum', '$n$', 'Malig.', 'LP', 'PFT', 'LoRA', 'CNN']
    return tabular('lrrcccc', header, rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()
    (OUT / 'tables').mkdir(parents=True, exist_ok=True)
    (OUT / 'figures').mkdir(parents=True, exist_ok=True)
    count = write_numbers(load_values())
    built = {'main_results': table_main(), 'cost': table_cost(), 'hypotheses': table_hypotheses(),
             'contrasts': table_contrasts(), 'ablations': table_ablations(),
             'error_strata': table_strata()}
    for name, text in built.items():
        header = ('%% Generated by scripts/make_latex.py from tables/. Do not edit.\n')
        (OUT / 'tables' / f'{name}.tex').write_text(header + text, encoding='utf-8', newline='\n')
    for name in FIGURES:
        shutil.copyfile(ROOT / 'figures' / f'{name}.png', OUT / 'figures' / f'{name}.png')
    bib = (ROOT / 'paper/refs.bib').read_text(encoding='utf-8')
    replaced = 0
    for character, escape_sequence in DIACRITICS.items():
        replaced += bib.count(character)
        bib = bib.replace(character, escape_sequence)
    remaining = sorted({c for c in bib if ord(c) > 127})
    if remaining:
        raise SystemExit('Unmapped non-ASCII in refs.bib: '
                         + ', '.join(f'U+{ord(c):04X} {c!r}' for c in remaining))
    (OUT / 'refs.bib').write_text(bib, encoding='utf-8', newline='\n')
    print(json.dumps({'macros': count, 'tables': sorted(built), 'figures': FIGURES,
                      'bib_diacritics_escaped': replaced,
                      'output': str(OUT.relative_to(ROOT))}, indent=2))


if __name__ == '__main__':
    main()
