"""Write the exact installed environment, including the CPU wheel source."""
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]

if __name__ == "__main__":
    subprocess.run([sys.executable, "-m", "pip", "check"], check=True)
    frozen = subprocess.check_output([sys.executable, "-m", "pip", "freeze", "--all"], text=True)
    header = "# Generated by scripts/lock_environment.py; CPU research environment.\n--extra-index-url https://download.pytorch.org/whl/cpu\n"
    (ROOT / "requirements.lock").write_text(header + frozen.replace("\r\n", "\n"), encoding="utf-8")
    print(f"Locked {len(frozen.splitlines())} installed distributions")
